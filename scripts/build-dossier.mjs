/**
 * Writes src/lib/dossier.generated.ts from site.ts and the project markdown.
 *
 * The chat endpoint is a Pages Function, bundled by esbuild rather than Vite,
 * so it cannot use `import.meta.glob` to pick the markdown up at import time.
 * Assembling the text here keeps the endpoint a plain module while leaving the
 * page's own data as the single source: edit site.ts or a write-up and the
 * dossier follows on the next build.
 *
 * Runs from `prebuild`, so `npm run build` and Cloudflare's own build both get
 * it without anyone remembering to.
 */
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

// Node strips the types on import, so the page's data file is read directly
// rather than duplicated or parsed.
const { profile, stack, roles, credentials, education, languages } = await import(
  path.join(root, "src/data/site.ts")
);

const projectsDir = path.join(root, "src/content/projects");
const files = (await readdir(projectsDir)).filter((f) => f.endsWith(".md")).sort();
const projects = await Promise.all(
  files.map(async (f) => (await readFile(path.join(projectsDir, f), "utf8")).trim())
);

const dossier = [
  `# ${profile.name}`,
  `${profile.role}, based in ${profile.location}.`,
  `Email: ${profile.email}`,
  `LinkedIn: ${profile.linkedin}`,
  `GitHub: ${profile.github}`,
  `Speaks: ${languages.join(", ")}`,
  "",
  "## In his own words",
  profile.statement,
  ...profile.intro,
  "",
  "## Technical skills, by layer",
  ...stack.map((row) => `${row.layer}: ${row.items.map((i) => i.name).join(", ")}`),
  "",
  "## Employment history",
  ...roles.map((role) =>
    [
      `### ${role.title}, ${role.company} (${role.place}) — ${role.period}`,
      role.summary,
      ...role.points.map((p) => `- ${p}`),
    ].join("\n")
  ),
  "",
  "## Selected project write-ups",
  ...projects,
  "",
  "## Certification",
  ...credentials.map((c) => `${c.title} — ${c.issuer}. ${c.note} (${c.url})`),
  "",
  "## Education",
  ...education.map((e) => `${e.title}, ${e.school}, ${e.period}`),
].join("\n");

const out = path.join(root, "src/lib/dossier.generated.ts");
await mkdir(path.dirname(out), { recursive: true });
await writeFile(
  out,
  "// Generated by scripts/build-dossier.mjs — do not edit.\n" +
    "// Edit src/data/site.ts or src/content/projects/*.md instead.\n" +
    `export const DOSSIER = ${JSON.stringify(dossier)};\n`
);

const approxTokens = Math.round(dossier.length / 3.7);
console.log(
  `[dossier] ${files.length} write-ups, ${dossier.length} chars (~${approxTokens} tokens) -> src/lib/dossier.generated.ts`
);
